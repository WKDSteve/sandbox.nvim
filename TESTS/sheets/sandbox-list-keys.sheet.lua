-- Live check: the container list view and its row keys, section 1 of ALL/manual-test-checklists/sandbox.md
-- (task sandbox.nvim/testblatt-bindings-checkliste). Fake engine CLIs (TESTS/sheets/_helpers.lua): every key must
-- reach the engine with the id of the row under the cursor; nothing is started.
return {
  id = "sandbox.list-keys",
  feature = "sandbox.container-list",
  title = "sandbox.nvim: container list rows, status colors, and every row key acting on the row under the cursor",
  task = "sandbox.nvim/manual-checklist-run",
  sizes = { { rows = 40, cols = 140 } },
  steps = {
    { lua = [[dofile(vim.fn.getcwd() .. "/TESTS/sheets/_helpers.lua")]] },
    { keys = ":Sandbox engine set docker<CR>" },
    { keys = ":Sandbox container list<CR>" },
    { wait = [[_G.bufname() == "sandbox.nvim://container-list" and _G.text() ~= ""]] },
    {
      expect = [[vim.deep_equal(vim.api.nvim_buf_get_lines(0, 0, -1, false), {
        "[running] sbx-web (aaa111aaa111)",
        "[exited] sbx-cache (ccc333ccc333)",
        "[exited] sbx-db (bbb222bbb222)",
        "[paused] sbx-paused (ddd444ddd444)",
      }) or error(_G.text(), 0)]],
      note = "running and stopped containers, running first, each with its [status]",
    },
    { expect = [[not vim.bo.modifiable and vim.bo.buftype == "nofile"]], note = "a read-only scratch buffer" },
    {
      expect = [[vim.deep_equal(_G.status_groups(), { "SandboxStatusRunning", "SandboxStatusStopped",
        "SandboxStatusStopped", "SandboxStatusPaused" }) or error(vim.inspect(_G.status_groups()), 0)]],
      note = "the prefix is colored by state",
    },

    { lua = [[_G.row("sbx-db"); _G.clear()]] },
    { keys = "s", note = "start, on the row under the cursor" },
    { wait = [[_G.called("docker start " .. _G.id("sbx-db")) == 1]] },
    { lua = [[_G.row("sbx-web")]] },
    { keys = "x" },
    { wait = [[_G.called("docker stop --time=1 " .. _G.id("sbx-web")) == 1]] },
    { keys = "R", note = "refresh: the states changed behind the list" },
    { wait = [[_G.text():find("[running] sbx-db", 1, true) and _G.text():find("[exited] sbx-web", 1, true)]] },
    { lua = [[_G.row("sbx-db")]] },
    { keys = "X", note = "kill asks first" },
    { wait = [[_G.float_has("Kill container " .. _G.id("sbx-db"))]] },
    { keys = "y" },
    { wait = [[_G.called("docker kill " .. _G.id("sbx-db")) == 1]] },
    { lua = [[_G.row("sbx-cache")]] },
    { keys = "r" },
    { wait = [[_G.called("docker restart " .. _G.id("sbx-cache")) == 1]] },
    { keys = "p" },
    { wait = [[_G.called("docker pause " .. _G.id("sbx-cache")) == 1]] },
    { keys = "P" },
    { wait = [[_G.called("docker unpause " .. _G.id("sbx-cache")) == 1]] },

    { keys = "<CR>", note = "inspect" },
    { wait = [[_G.bufname() == "sandbox.nvim://inspect/" .. _G.id("sbx-cache")]] },
    { expect = [[_G.has(_G.text(), '"/sbx-cache"')]], note = "the engine's own metadata" },
    { keys = "q" },
    { wait = [[_G.buf("sandbox.nvim://inspect/" .. _G.id("sbx-cache")) == nil or vim.fn.winnr("$") == 1]] },
    { lua = [[_G.row("sbx-web")]] },
    { keys = "i" },
    { wait = [[_G.bufname() == "sandbox.nvim://inspect/" .. _G.id("sbx-web")]] },
    { keys = "q" },

    { lua = [[_G.row("sbx-web")]] },
    { keys = "l", note = "logs" },
    { wait = [[_G.bufname() == "sandbox.nvim://logs/" .. _G.id("sbx-web")]] },
    { expect = [[_G.has(_G.text(), "log line one of " .. _G.id("sbx-web"))]] },
    { lua = [[_G.row("sbx-web")]] },
    { keys = "t", note = "top" },
    { wait = [[_G.called("docker top " .. _G.id("sbx-web")) == 1 and _G.text():find("sleep 300", 1, true) ~= nil]] },
    { lua = [[_G.row("sbx-web")]] },
    { keys = "T", note = "stats" },
    { wait = [[_G.called("docker stats --no-stream " .. _G.id("sbx-web")) == 1 and _G.text():find("0.01%", 1, true)]] },
    { lua = [[_G.row("sbx-web")]] },
    { keys = "e", note = "exec: a terminal on the engine's exec" },
    { wait = [[_G.bufname() == "sandbox.nvim://exec/" .. _G.id("sbx-web") and vim.bo.buftype == "terminal"]] },
    { expect = [[_G.last("docker exec").argv == "docker exec -it " .. _G.id("sbx-web") .. " sh"]] },
    { lua = [[vim.cmd("stopinsert"); _G.row("sbx-web")]] },
    { wait = [[vim.fn.mode() == "n"]] },

    { input = "n", note = "rename prompts for the new name (input: keys would end the insert mode it opens in)" },
    { wait = [[_G.in_float() and vim.fn.mode() == "i"]] },
    { input = "sbx-renamed" },
    { wait = [[vim.api.nvim_get_current_line():find("sbx-renamed", 1, true) ~= nil]] },
    { input = "<CR>" },
    { wait = [[_G.called("docker rename " .. _G.id("sbx-web") .. " sbx-renamed") == 1]] },
    { lua = [[vim.cmd("stopinsert"); _G.row("sbx-paused")]] },
    { wait = [[vim.fn.mode() == "n"]] },
    { keys = "D", note = "remove asks first" },
    {
      wait = [[_G.float_has("Remove container " .. _G.id("sbx-paused"))]],
    },
    { expect = [[_G.called("docker rm " .. _G.id("sbx-paused")) == 0]], note = "nothing removed before the answer" },
    { keys = "y" },
    { wait = [[_G.called("docker rm " .. _G.id("sbx-paused")) == 1]] },
    { expect = [[#_G.other_spawns == 0 or error(vim.inspect(_G.other_spawns))]], note = "no real process" },
  },
  manual = {
    "against a real engine: the colors track a real running and a real stopped container, and start/stop, "
      .. "inspect, logs and exec act on that container",
  },
}
